function t(key) {
  const lang = I18N[APP_LANG] || I18N.tr;
  return lang[key] !== undefined ? lang[key] : (I18N.tr[key] !== undefined ? I18N.tr[key] : key);
}

// Percent, placed per language convention: "%40" (tr) vs "40%" (en).
function formatPct(n) {
  return APP_LANG === "en" ? `${n}%` : `%${n}`;
}

// t() with {placeholder} substitution.
function tf(key, params) {
  let s = t(key);
  Object.keys(params).forEach((k) => { s = s.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]); });
  return s;
}

