// Lightweight TR/EN i18n. UI chrome is translated; user-entered data stays
// as typed. Language is stored in localStorage; toggling switches all UI
// text immediately (Session 30) — the root App re-renders on the
// "yk-lang-change" event, and every component reads t() during render.

let APP_LANG = (() => {
  try { return localStorage.getItem("yasamkocu_lang") === "en" ? "en" : "tr"; }
  catch (e) { return "tr"; }
})();

function appLocale() {
  return APP_LANG === "en" ? "en-US" : "tr-TR";
}

// Keep <html lang> in sync so CSS text-transform: uppercase uses the right
// locale — otherwise Turkish casing turns English "Timer" into "TİMER".
function applyHtmlLang() {
  if (typeof document !== "undefined") document.documentElement.lang = APP_LANG;
}
applyHtmlLang();

function toggleAppLang() {
  APP_LANG = APP_LANG === "en" ? "tr" : "en";
  localStorage.setItem("yasamkocu_lang", APP_LANG);
  applyHtmlLang();
  window.dispatchEvent(new Event("yk-lang-change"));
}

